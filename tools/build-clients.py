#!/usr/bin/env python3
"""Rebuild the clients bar in index.html and academy.html from data/clients.json.
The bar is static HTML (works without JavaScript and is visible to search engines)."""
import html, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = json.load(open(os.path.join(ROOT, 'data', 'clients.json'), encoding='utf-8'))

def row(names, cls, label):
    items = ''.join(f'<li>{html.escape(n)}</li>' for n in names)
    dup = ''.join(f'<li aria-hidden="true">{html.escape(n)}</li>' for n in names)
    return (f'<div class="cb-row {cls}"><p class="cb-label">{label}</p>'
            f'<div class="cb-track"><ul class="cb-list">{items}{dup}</ul></div></div>')

block = ('<!-- clients-bar:start (generated by tools/build-clients.py) -->\n'
         '        <section class="clients-bar" aria-labelledby="cb-title">\n'
         '            <div class="container cb-head"><h2 id="cb-title">Teams we have trained, and the organisers we teach with</h2>'
         '<button type="button" class="cb-pause" aria-pressed="false">Pause</button></div>\n'
         '            ' + row(data['clients'], 'cb-clients', 'In-house training clients') + '\n'
         '            ' + row(data['partners'], 'cb-partners', 'Programme partners and organisers') + '\n'
         '            <p class="container cb-note">Names are listed for identification only and do not imply endorsement.</p>\n'
         '        </section>\n'
         '        <!-- clients-bar:end -->')

for page, anchor in (('index.html', '        <!-- Pillars -->'), ('academy.html', '        <section class="programmes-section" id="courses">')):
    p = os.path.join(ROOT, page)
    s = open(p, encoding='utf-8').read()
    if '<!-- clients-bar:start' in s:
        s = re.sub(r'<!-- clients-bar:start.*?<!-- clients-bar:end -->', block, s, flags=re.S)
    else:
        s = s.replace(anchor, '        ' + block + '\n\n' + anchor, 1)
    open(p, 'w', encoding='utf-8').write(s)
    print('clients bar ->', page)
